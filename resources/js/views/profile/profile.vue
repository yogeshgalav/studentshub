<template>
    <div>
        <div class="container pt-100">
            <div class="user_profile_page">
                <div class="row">
                    <div class="col-md-8 center-col">
                        <div class="row">
                            <div class="col-md-3">
                                <div class="user_profile_img">
                                    <img v-if="user.avatar_url" :src="user.avatar_url" alt="">
                                    <img v-else src="/images/default-avatar.png" alt="">
                                </div>
                            </div>
                            <div class="col-md-9">
                                <div class="user_des">
                                    <h3 class="user_profile_name"> {{user.full_name}} <span @click="openProfileEditModal"><i class="fas fa-edit"></i></span></h3>
                                    <p>{{user.introduction}}</p>
                                    <p v-if="!user.introduction">Write Something about yourself. What are your hobbies. 
                                        What field are you most interested in.Which is your favriout subject.
                                        Why do you love it and what motivates you to pursue it.</p>
                                </div>
                                <div class="user_social_links">
                                    <div class="user_social_link_left">
                                        <span><a :href="user.fb_url ? user.fb_url :'#'" target="_blank"><i class="fab fa-facebook-f"></i></a></span>
                                        <span><a :href="user.insta_url ? user.fb_url :'#'" target="_blank"><i class="fab fa-instagram"></i></a></span>
                                        <span><a :href="user.linkedin_url ? user.fb_url :'#'" target="_blank"><i class="fab fa-linkedin"></i></a></span>
                                        <span><a :href="user.email ? 'mailto:'+user.email :'#'" target="_blank"><i class="fa fa-envelope"></i></a></span>

                                    </div>
                                </div>
                            </div>
                        </div>
                    </div>
                </div>
                <div class="user_interest">
                    <h4>Your Interest</h4>
                    <div class="user_int">
                        <div class="user_int_text">
                            <p>This data is generated by your interaction with posts,hence the more you interect with
                                posts the more
                                precise this data is.</p>
                            <p v-if="interests.length===0">Currently we don't have enough data to analys your interest.
                                Please share at least 3 Posts to generate this data.</p>
                        </div>
                        <div class="progess_bar">
                        <div class="cojl" v-for="(interest,index) in interests" :key="index">
                            <radial-progress-bar :diameter="150" :completed-steps="interest.percent" :total-steps="100"
                                :startColor="'#00BFFF'" :stopColor="'#000080'" :innerStrokeColor="'#B0E0E6'">
                                <p class="counter-count">{{ interest.percent }}</p>
